import type { World } from "./types.ts";

export const FOUNDING_COVEN_ID = "00000000-0000-4000-8000-000000000001";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const b = (v: boolean | undefined) => (v ? "true" : "false");
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

// Idempotent: safe to re-run against an existing database. Content upserts; witches are never reset once created.
// Rooms, items and activities that disappeared from the world are switched off rather than deleted, so history stays intact.
export function buildSeedSql(w: World): string {
  const lines: string[] = [
    "-- GENERATED by `npm run build:world` (or scripts/gen-seed.ts) from lib/game/catalog.ts. Do not edit by hand.",
    "begin;",
    "",
    `insert into public.covens (id, slug, name) values (${q(FOUNDING_COVEN_ID)}, ${q(w.meta.slug)}, ${q(w.meta.name)}) on conflict (id) do update set slug = excluded.slug, name = excluded.name;`,
    "",
  ];

  // Tunable in the Owner screen: written once, never overwritten by a reseed.
  const { daily_loot, ...tunable } = w.gameConfig;
  for (const [key, value] of Object.entries(tunable)) {
    lines.push(`insert into public.game_config (key, value) values (${q(key)}, ${j(value)}) on conflict (key) do nothing;`);
  }
  // Shaped by the world: always refreshed from the catalog.
  const content = {
    daily_loot,
    day_timezone: w.meta.timezone,
    start_location: w.meta.startLocation,
    currency: w.meta.currency,
    flavour: w.meta.flavour,
    shared_events: w.sharedEvents,
    gift_treats: w.giftTreats.map(({ id, name, cost, effects }) => ({ id, name, cost, effects })),
    coven_goals: w.covenGoals,
    coven_goal_reward: w.covenGoalReward,
    oracle_cards: w.oracleCards.map((c) => c.id),
  };
  for (const [key, value] of Object.entries(content)) {
    lines.push(`insert into public.game_config (key, value) values (${q(key)}, ${j(value)}) on conflict (key) do update set value = excluded.value;`);
  }
  lines.push("");

  for (const l of w.locations) {
    lines.push(`insert into public.locations (id, name, blurb) values (${q(l.id)}, ${q(l.name)}, ${q(l.blurb)}) on conflict (id) do update set name = excluded.name, blurb = excluded.blurb;`);
  }
  lines.push("");

  for (const i of w.items) {
    lines.push(`insert into public.items (id, name, category, slot, price, placeable, rarity, description, season, active) values (${q(i.id)}, ${q(i.name)}, ${q(i.category)}, ${q(i.slot)}, ${n(i.price)}, ${b(i.placeable)}, ${q(i.rarity)}, ${q(i.description)}, ${i.season ? `array[${i.season.join(", ")}]::int[]` : "null"}, true) on conflict (id) do update set name = excluded.name, category = excluded.category, slot = excluded.slot, price = excluded.price, placeable = excluded.placeable, rarity = excluded.rarity, description = excluded.description, season = excluded.season, active = true;`);
  }
  lines.push(`update public.items set active = false where id <> all (${arr(w.items.map((i) => i.id))});`);
  lines.push("");

  for (const a of w.activities) {
    const loot = (a.loot ?? []).map((l) => ({ item_id: l.itemId, chance: l.chance }));
    lines.push(`insert into public.activities (id, location_id, name, category, effects, coins, xp, cooldown_seconds, adult_only, loot, animation, flavour_count, active) values (${q(a.id)}, ${q(a.locationId)}, ${q(a.name)}, ${q(a.category)}, ${j(a.effects)}, ${a.coins}, ${a.xp}, ${a.cooldownSeconds}, ${b(a.adultOnly)}, ${j(loot)}, ${q(a.animation)}, ${a.flavour.length}, true) on conflict (id) do update set location_id = excluded.location_id, name = excluded.name, category = excluded.category, effects = excluded.effects, coins = excluded.coins, xp = excluded.xp, cooldown_seconds = excluded.cooldown_seconds, adult_only = excluded.adult_only, loot = excluded.loot, animation = excluded.animation, flavour_count = excluded.flavour_count, active = true;`);
  }
  lines.push(`update public.activities set active = false where id <> all (${arr(w.activities.map((a) => a.id))});`);
  lines.push("");

  for (const a of w.achievements) {
    lines.push(`insert into public.achievements (id, name, description) values (${q(a.id)}, ${q(a.name)}, ${q(a.description)}) on conflict (id) do update set name = excluded.name, description = excluded.description;`);
  }
  lines.push("");

  for (const c of w.characters) {
    lines.push(`insert into public.characters (id, coven_id, name, title, pronoun_subject, pronoun_object, pronoun_possessive, pronoun_plural, young, is_owner_character, description, personality, look, default_equipped, starter_items) values (${q(c.id)}, ${q(FOUNDING_COVEN_ID)}, ${q(c.name)}, ${q(c.title)}, ${q(c.pronouns.subject)}, ${q(c.pronouns.object)}, ${q(c.pronouns.possessive)}, ${b(c.pronouns.plural)}, ${b(c.young)}, ${b(c.isOwnerCharacter)}, ${q(c.description)}, ${q(c.personality)}, ${j(c.look)}, ${j(c.equipped)}, ${arr(c.starterItems)}) on conflict (id) do update set default_equipped = excluded.default_equipped, starter_items = excluded.starter_items, young = excluded.young, is_owner_character = excluded.is_owner_character;`);
  }
  lines.push("");
  lines.push("-- Initialise each witch once (stats, starter wardrobe, room). Never resets an existing witch.");
  for (const c of w.characters) {
    lines.push(`select game.init_character(${q(c.id)}) where not exists (select 1 from public.character_stats where character_id = ${q(c.id)});`);
  }
  lines.push("", "commit;", "");
  return lines.join("\n");
}
