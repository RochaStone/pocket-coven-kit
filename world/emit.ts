// Writes a World out as lib/game/catalog.ts, the module the game imports.
import type { World } from "../lib/game/types.ts";

const j = (v: unknown) => JSON.stringify(v, null, 2);

export function catalogSource(w: World, from: string): string {
  return `// GENERATED by \`npm run build:world\` from ${from}. Do not edit by hand: edit the config and rebuild.
// supabase/seed.sql is generated from this file; tests fail if the two drift.
import type { AchievementDef, ActivityDef, CharacterDef, CovenGoalDef, GameConfig, GiftTreatDef, ItemDef, LocationDef, OracleCardDef, SharedEventDef, World, WorldMeta } from "./types.ts";

export const WORLD: WorldMeta = ${j(w.meta)};

export const CHARACTERS: CharacterDef[] = ${j(w.characters)};

export const ITEMS: ItemDef[] = ${j(w.items)};

export const LOCATIONS: LocationDef[] = ${j(w.locations)};

export const ACTIVITIES: ActivityDef[] = ${j(w.activities)};

export const SHARED_EVENTS: Record<string, SharedEventDef> = ${j(w.sharedEvents)};

export const ACHIEVEMENTS: AchievementDef[] = ${j(w.achievements)};

export const GIFT_TREATS: GiftTreatDef[] = ${j(w.giftTreats)};

export const COVEN_GOALS: CovenGoalDef[] = ${j(w.covenGoals)};

export const COVEN_GOAL_REWARD = ${j(w.covenGoalReward)};

export const ORACLE_CARDS: OracleCardDef[] = ${j(w.oracleCards)};

export const GAME_CONFIG: GameConfig = ${j(w.gameConfig)};

export const CATALOG: World = {
  meta: WORLD,
  characters: CHARACTERS,
  items: ITEMS,
  locations: LOCATIONS,
  activities: ACTIVITIES,
  sharedEvents: SHARED_EVENTS,
  achievements: ACHIEVEMENTS,
  giftTreats: GIFT_TREATS,
  covenGoals: COVEN_GOALS,
  covenGoalReward: COVEN_GOAL_REWARD,
  oracleCards: ORACLE_CARDS,
  gameConfig: GAME_CONFIG,
};

export const itemById = (id: string) => ITEMS.find((i) => i.id === id);
export const activityById = (id: string) => ACTIVITIES.find((a) => a.id === id);
export const locationById = (id: string) => LOCATIONS.find((l) => l.id === id);
export const characterById = (id: string) => CHARACTERS.find((c) => c.id === id);
export const treatById = (id: string) => GIFT_TREATS.find((t) => t.id === id);
export const currencyLabel = (n: number) => \`\${n} \${n === 1 ? WORLD.currency.singular : WORLD.currency.plural}\`;
`;
}
